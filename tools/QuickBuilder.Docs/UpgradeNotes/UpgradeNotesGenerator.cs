extern alias releasetool;

using System.Text;
using QuickBuilder.Docs.Settings;
using Fragment = releasetool::QuickBuilder.Release.Fragment;
using ReleaseRuleException = releasetool::QuickBuilder.Release.ReleaseRuleException;
using SemanticVersion = releasetool::QuickBuilder.Shared.Infrastructure.Versioning.SemanticVersion;

namespace QuickBuilder.Docs.UpgradeNotes;

/// <summary>
/// <c>upgrade-notes generate</c>: every release's upgrade notes on one operator page, newest
/// first (026 research OD-16; FR-028). Built from the same release-note fragments as 019's
/// notes: <c>docs/releases/&lt;version&gt;/</c> for released versions and
/// <c>docs/releases/unreleased/</c> for the release being prepared.
/// </summary>
internal static class UpgradeNotesGenerator
{
    public const string PagePath = "docs/operators/upgrade-notes.md";

    private const string GeneratedComment =
        "<!-- Generated by qb-docs upgrade-notes generate. Do not edit; see docs/contributing.md#operator-docs -->";

    private const string None = "None.";

    public static int Run(string repositoryRoot, string? through, TextWriter output, TextWriter error)
    {
        SemanticVersion last;
        try
        {
            last = through is null ? NextRelease(repositoryRoot) : SemanticVersion.Parse(through);
        }
        catch (FormatException)
        {
            error.WriteLine($"--through: '{through}' is not a version like 0.2.0 — pass the release being prepared.");
            return Program.UsageError;
        }

        string page;
        try
        {
            page = Render(repositoryRoot, last);
        }
        catch (ReleaseRuleException e)
        {
            error.WriteLine(e.Message);
            return Program.Failed;
        }

        var target = Path.Combine(repositoryRoot, PagePath);
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        File.WriteAllText(target, page);
        output.WriteLine($"Wrote {PagePath} through {last}.");
        return Program.Pass;
    }

    /// <summary>The release being prepared: <c>VersionPrefix</c> in <c>Directory.Build.props</c>.</summary>
    public static SemanticVersion NextRelease(string repositoryRoot)
    {
        var props = File.ReadAllText(Path.Combine(repositoryRoot, "Directory.Build.props"));
        var start = props.IndexOf("<VersionPrefix>", StringComparison.Ordinal) + "<VersionPrefix>".Length;
        var end = props.IndexOf("</VersionPrefix>", start, StringComparison.Ordinal);
        return SemanticVersion.Parse(props[start..end].Trim());
    }

    /// <exception cref="ReleaseRuleException">A fragment is malformed.</exception>
    public static string Render(string repositoryRoot, SemanticVersion through)
    {
        var releases = Path.Combine(repositoryRoot, "docs", "releases");
        var versions = Directory.Exists(releases)
            ? Directory.EnumerateDirectories(releases)
                .Select(d => (Directory: d, Name: Path.GetFileName(d)))
                .Where(d => SemanticVersion.TryParse(d.Name, out var v) && !v.IsPreRelease && v <= through)
                .Select(d => (d.Directory, Version: SemanticVersion.Parse(d.Name)))
                .ToList()
            : [];

        if (!versions.Any(v => v.Version == through))
        {
            versions.Add((Path.Combine(releases, "unreleased"), through));
        }

        var text = new StringBuilder();
        text.Append(GeneratedComment).Append("\n\n");
        text.Append("# Upgrade notes\n\n");
        text.Append("What each release asks of an operator, newest first. Before upgrading, read the notes of\n");
        text.Append("every release after the one you run, up to the one you are moving to, then follow\n");
        text.Append("[Upgrade](upgrade.md). A section that does not apply says \"None.\"\n");

        foreach (var (directory, version) in versions.OrderByDescending(v => v.Version))
        {
            var fragments = Directory.Exists(directory)
                ? Directory.EnumerateFiles(directory, "*.md")
                    .Select(f => Fragment.Parse(f, File.ReadAllText(f)))
                    .OrderBy(f => f.Issue)
                    .ThenBy(f => f.File, StringComparer.Ordinal)
                    .ToList()
                : [];

            text.Append('\n').Append($"<a id=\"{Anchor(version)}\"></a>\n\n");
            text.Append($"## QuickBuilder {version}\n");
            Section(text, "Breaking changes", fragments.Where(f => f.Breaking).Select(f => $"{f.Summary} (#{f.Issue})"));
            Section(text, "Manual steps", fragments.SelectMany(f => f.Manual.Select(m => $"{m} (#{f.Issue})")));
            Section(text, "Configuration", Configuration(fragments));
            Section(text, "Background work after upgrading", fragments.SelectMany(f => f.Background.Select(m => $"{m} (#{f.Issue})")));
            Section(text, "Caches", fragments.SelectMany(f => f.Caches.Select(m => $"{m} (#{f.Issue})")));
        }

        return text.ToString();
    }

    /// <summary>The anchor of a release's notes, e.g. <c>0-2-0</c> for 0.2.0.</summary>
    public static string Anchor(SemanticVersion version) => version.ToString().Replace('.', '-');

    private static IEnumerable<string> Configuration(IReadOnlyList<Fragment> fragments)
    {
        foreach (var fragment in fragments)
        {
            foreach (var key in fragment.ConfigAdded)
            {
                yield return $"Added {Link(key)} (#{fragment.Issue})";
            }

            foreach (var key in fragment.ConfigChanged)
            {
                yield return $"Changed {Link(key)} (#{fragment.Issue})";
            }

            foreach (var key in fragment.ConfigDeprecated)
            {
                yield return $"Deprecated {Link(key)} (#{fragment.Issue})";
            }

            foreach (var key in fragment.ConfigRemoved)
            {
                yield return $"Removed `{key}` (#{fragment.Issue})";
            }
        }
    }

    private static string Link(string key) => $"[`{key}`](reference/configuration.md#{SettingDefinition.AnchorFor(key)})";

    private static void Section(StringBuilder text, string title, IEnumerable<string> items)
    {
        var list = items.ToList();
        text.Append('\n').Append("### ").Append(title).Append("\n\n");
        if (list.Count == 0)
        {
            text.Append(None).Append('\n');
            return;
        }

        foreach (var item in list)
        {
            text.Append("- ").Append(item).Append('\n');
        }
    }
}
