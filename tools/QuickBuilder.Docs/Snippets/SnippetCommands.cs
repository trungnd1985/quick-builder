using System.Text;

namespace QuickBuilder.Docs.Snippets;

/// <summary><c>snippets list</c> and <c>snippets write</c> (026 contracts/qb-docs-cli.md).</summary>
internal static class SnippetCommands
{
    public const string DocsRoot = "docs/operators";

    /// <summary>Every marked block of every operator page, and every marker error.</summary>
    public static (IReadOnlyList<Snippet> Snippets, List<string> Problems) Collect(string repositoryRoot)
    {
        var problems = new List<string>();
        var snippets = new List<Snippet>();
        foreach (var page in Pages(repositoryRoot))
        {
            var relative = Path.GetRelativePath(repositoryRoot, page).Replace('\\', '/');
            snippets.AddRange(MarkerParser.Parse(relative, File.ReadAllText(page), problems));
        }

        MarkerParser.CheckProcedures(snippets, problems);
        return (snippets, problems);
    }

    /// <summary>Operator pages: Markdown under <see cref="DocsRoot"/>, without dependencies or build output.</summary>
    public static IEnumerable<string> Pages(string repositoryRoot)
    {
        var root = Path.Combine(repositoryRoot, DocsRoot);
        return Directory.Exists(root)
            ? Directory.EnumerateFiles(root, "*.md", SearchOption.AllDirectories)
                .Where(p => !p.Contains($"{Path.DirectorySeparatorChar}node_modules{Path.DirectorySeparatorChar}", StringComparison.Ordinal)
                            && !p.Contains($"{Path.DirectorySeparatorChar}.vitepress{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
                .Order(StringComparer.Ordinal)
            : [];
    }

    public static int List(string repositoryRoot, string? procedure, TextWriter output, TextWriter error)
    {
        var (snippets, problems) = Collect(repositoryRoot);
        if (Report(problems, error))
        {
            return Program.Failed;
        }

        foreach (var group in snippets.Where(s => procedure is null || s.Procedure == procedure).GroupBy(s => s.Procedure).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            output.WriteLine(group.Key);
            foreach (var snippet in group.OrderBy(s => s.Step))
            {
                var what = snippet.Kind == "file" ? $"file {snippet.FilePath}" : "run";
                var substitute = snippet.Substitutes.Count == 0 ? string.Empty : $" (substitute={string.Join(',', snippet.Substitutes)})";
                output.WriteLine($"  {snippet.Step,3} {what}{substitute} — {snippet.Source}:{snippet.Line}");
            }
        }

        return Program.Pass;
    }

    public static int Write(
        string repositoryRoot,
        string procedure,
        string directory,
        IReadOnlyDictionary<string, string> substitutions,
        TextWriter output,
        TextWriter error)
    {
        var (snippets, problems) = Collect(repositoryRoot);
        var steps = snippets.Where(s => s.Procedure == procedure).OrderBy(s => s.Step).ToList();
        if (steps.Count == 0 && problems.Count == 0)
        {
            problems.Add($"{procedure}: no marked blocks — mark the page's commands with <!-- qb:run procedure={procedure} step=<n> -->.");
        }

        foreach (var unknown in substitutions.Keys.Where(k => !Substitutions.Names.Contains(k)))
        {
            problems.Add($"--substitute {unknown}: unknown substitution — use one of {string.Join(", ", Substitutions.Names)}.");
        }

        var script = new StringBuilder("#!/usr/bin/env bash\n# Generated by qb-docs snippets write from the operator documentation.\nset -euo pipefail\n");
        var files = new List<(string Path, string Body)>();
        var matched = new HashSet<string>(StringComparer.Ordinal);
        foreach (var step in steps)
        {
            var where = $"{step.Source}:{step.Line}";
            var body = step.Body;
            var applied = true;
            foreach (var name in step.Substitutes)
            {
                if (!substitutions.TryGetValue(name, out var value))
                {
                    problems.Add($"{where}: needs --substitute {name}=<value>.");
                    applied = false;
                    break;
                }

                if (Substitutions.Apply(name, value, body, where, problems, matched) is not { } replaced)
                {
                    applied = false;
                    break;
                }

                body = replaced;
            }

            if (!applied)
            {
                continue;
            }

            if (step.Kind == "file")
            {
                files.Add((step.FilePath!, body));
            }
            else
            {
                script.Append('\n').Append($"# step {step.Step} — {where}").Append('\n').Append(body).Append('\n');
            }
        }

        // A pair substitution may span several blocks; each pair must have matched one of them.
        foreach (var (name, value) in substitutions.Where(s => s.Key is Substitutions.TestCertificates or Substitutions.HostNames or Substitutions.Ports))
        {
            foreach (var from in value.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Select(p => p.Split('>', 2)[0]))
            {
                if (steps.Any(s => s.Substitutes.Contains(name)) && !matched.Contains($"{name}:{from}"))
                {
                    problems.Add($"{procedure}: substitution {name} expected '{from}' in a block marked substitute={name} — the page changed; update the test's substitution.");
                }
            }
        }

        if (Report(problems, error))
        {
            return Program.Failed;
        }

        Directory.CreateDirectory(directory);
        foreach (var (path, body) in files)
        {
            var target = Path.Combine(directory, path);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllText(target, body.EndsWith('\n') ? body : body + "\n");
        }

        File.WriteAllText(Path.Combine(directory, "run.sh"), script.ToString());
        output.WriteLine($"Wrote {procedure}: {files.Count} files and run.sh with {steps.Count(s => s.Kind == "run")} steps to {directory}.");
        return Program.Pass;
    }

    private static bool Report(List<string> problems, TextWriter error)
    {
        foreach (var problem in problems)
        {
            error.WriteLine(problem);
        }

        return problems.Count > 0;
    }
}
